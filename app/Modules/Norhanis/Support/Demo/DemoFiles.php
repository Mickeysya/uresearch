<?php

namespace App\Modules\Norhanis\Support\Demo;

/**
 * Placeholder files for the demo data: a small, valid one-page PDF per
 * document field ("DEMO PLACEHOLDER - Invoice") and a small PNG for claim
 * receipts, each built once and reused. They are stored through Core's
 * DocumentStore, on the private local disk, like any upload.
 */
final class DemoFiles
{
    /** @var array<string, string> */
    protected array $pdfs = [];

    protected ?string $png = null;

    protected ?string $signature = null;

    /** A one-page PDF saying what it stands in for. */
    public function pdf(string $title): string
    {
        return $this->pdfs[$title] ??= self::buildPdf('DEMO PLACEHOLDER - '.$title, 'Generated by norhanis:demo-seed. Not a real document.');
    }

    /** A small PNG "receipt". */
    public function png(): string
    {
        if ($this->png !== null) {
            return $this->png;
        }

        $image = imagecreatetruecolor(240, 120);
        imagefill($image, 0, 0, imagecolorallocate($image, 255, 255, 255));
        $ink = imagecolorallocate($image, 40, 40, 40);
        imagerectangle($image, 2, 2, 237, 117, $ink);
        imagestring($image, 4, 20, 30, 'DEMO RECEIPT', $ink);
        imagestring($image, 2, 20, 60, 'Placeholder - not a real receipt', $ink);

        ob_start();
        imagepng($image);
        $this->png = (string) ob_get_clean();
        imagedestroy($image);

        return $this->png;
    }

    /** A drawn squiggle as a signature: base64 PNG, as SignatureImage stores it. */
    public function signature(): string
    {
        if ($this->signature !== null) {
            return $this->signature;
        }

        $image = imagecreatetruecolor(300, 100);
        imagesavealpha($image, true);
        imagefill($image, 0, 0, imagecolorallocatealpha($image, 255, 255, 255, 127));
        $ink = imagecolorallocate($image, 20, 30, 90);
        imagesetthickness($image, 3);

        $x = 20;
        $y = 60;
        for ($i = 0; $i < 9; $i++) {
            $nx = $x + 28;
            $ny = 30 + (($i * 37) % 50);
            imageline($image, $x, $y, $nx, $ny, $ink);
            [$x, $y] = [$nx, $ny];
        }

        ob_start();
        imagepng($image);
        $this->signature = base64_encode((string) ob_get_clean());
        imagedestroy($image);

        return $this->signature;
    }

    /** A minimal valid PDF 1.4 with two lines of Helvetica text. */
    protected static function buildPdf(string $title, string $line): string
    {
        $escape = fn (string $text) => str_replace(['\\', '(', ')'], ['\\\\', '\\(', '\\)'], $text);
        $stream = "BT /F1 16 Tf 60 760 Td ({$escape($title)}) Tj ET\nBT /F1 10 Tf 60 736 Td ({$escape($line)}) Tj ET";

        $objects = [
            '<< /Type /Catalog /Pages 2 0 R >>',
            '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
            '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
            '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
            '<< /Length '.strlen($stream)." >>\nstream\n{$stream}\nendstream",
        ];

        $pdf = "%PDF-1.4\n";
        $offsets = [];
        foreach ($objects as $i => $object) {
            $offsets[] = strlen($pdf);
            $pdf .= ($i + 1)." 0 obj\n{$object}\nendobj\n";
        }

        $xref = strlen($pdf);
        $pdf .= 'xref'."\n0 ".(count($objects) + 1)."\n0000000000 65535 f \n";
        foreach ($offsets as $offset) {
            $pdf .= sprintf("%010d 00000 n \n", $offset);
        }

        return $pdf.'trailer'."\n<< /Size ".(count($objects) + 1)." /Root 1 0 R >>\nstartxref\n{$xref}\n%%EOF\n";
    }
}
